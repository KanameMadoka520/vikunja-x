import {test, expect} from '../../support/fixtures'
import {createProjects} from '../project/prepareProjects'
import {TaskFactory} from '../../factories/task'
import {UserFactory} from '../../factories/user'
import {login} from '../../support/authenticateUser'
import {apiRootUrl} from '../../support/apiUrl'

for (const width of [1440, 390]) {
 test(`Drive reuse, usages, recycle and permanent deletion at ${width}px`, async ({authenticatedPage: page, apiContext}) => {
  test.setTimeout(60_000)
  await createProjects(1)
  await TaskFactory.create(1, {title: 'Drive reference task'})
  await page.setViewportSize({width, height: 900})
  await page.goto('/drive')
  await expect(page.getByRole('heading', {name: 'My Drive'})).toBeVisible()
  const root = apiRootUrl(process.env.API_URL || 'http://127.0.0.1:3456') + '/api/v2'
  const token = await page.evaluate(() => localStorage.getItem('token'))
  const headers = {Authorization: `Bearer ${token}`}
  const uploaded = page.waitForResponse(r => r.url().endsWith('/drive/files') && r.request().method() === 'POST')
  await page.locator('.drive-browser input[type=file]').setInputFiles({name: 'reusable.txt', mimeType: 'text/plain', buffer: Buffer.from('one original, many references')})
  const uploadResponse = await uploaded
  expect(uploadResponse.status()).toBe(200)
  const file = await uploadResponse.json()
  await expect(page.locator('.drive-card')).toHaveCount(1)
  await page.locator('.drive-card').getByRole('button', {name: 'Details and usages', exact: true}).click()
  const details = page.getByRole('dialog', {name: 'Details and usages'})
  await details.getByLabel('Category', {exact: true}).fill('Work')
  await details.getByLabel('Pin this file').check()
  await details.getByRole('button', {name: 'Save', exact: true}).click()
  await expect(details).not.toBeVisible()
  await page.reload()
  await expect(page.locator('.drive-card')).toContainText('★ reusable.txt')
  await expect(page.locator('.drive-card')).toContainText('Work')
  await page.goto('/tasks/1')
  await page.getByRole('button', {name: 'Choose from Drive', exact: true}).click()
  const picker = page.getByRole('dialog', {name: 'Choose from Drive'})
  await picker.getByRole('button', {name: 'Choose from Drive', exact: true}).click()
  await expect(picker).not.toBeVisible()
  await expect(page.locator('.content.attachments')).toContainText('reusable.txt')
  const files = await (await apiContext.get(`${root}/drive/files`, {headers})).json()
  expect(files.total).toBe(1)
  expect(files.files[0].file_id).toBe(file.file_id)
  const second = (await UserFactory.create(1, {id: 2, username: 'drive-other'}, false))[0]
  const {token: otherToken} = await login(null, apiContext, second)
  expect((await apiContext.get(`${root}/drive/files/${file.file_id}/download`, {headers: {Authorization: `Bearer ${otherToken}`}})).status()).toBe(404)
  expect((await apiContext.get(`${root}/drive/files/${file.file_id}/usages`, {headers: {Authorization: `Bearer ${otherToken}`}})).status()).toBe(404)
  await page.goto('/drive')
  await page.locator('.drive-card').getByRole('button', {name: 'Move to recycle bin', exact: true}).click()
  await expect(details).toContainText('Drive reference task')
  const move = details.getByRole('button', {name: 'Move to recycle bin', exact: true})
  await expect(move).toBeDisabled()
  await details.getByRole('checkbox', {name: 'I have reviewed the usages and confirm moving this file to the recycle bin.'}).check()
  await move.click()
  await expect(details).not.toBeVisible()
  await expect(page.locator('.drive-card')).toHaveCount(0)
  const recycled = await (await apiContext.get(`${root}/drive/files?trash=true`, {headers})).json()
  expect(recycled.total).toBe(1)
  expect((await apiContext.post(`${root}/drive/files/${file.file_id}/attach`, {headers, data: {revision: recycled.files[0].revision, task_id: 1}})).status()).toBe(409)
  const task = await (await apiContext.get(`${root}/tasks/1`, {headers})).json()
  const attachment = task.attachments[0]
  expect((await apiContext.get(`${root}/tasks/1/attachments/${attachment.id}`, {headers})).status()).toBe(200)
  await page.locator('.drive-toolbar').getByRole('button', {name: 'Recycle bin', exact: true}).click()
  await page.locator('.drive-card').getByRole('button', {name: 'Details and usages', exact: true}).click()
  await expect(details.getByRole('button', {name: 'Delete permanently', exact: true})).toBeDisabled()
  await details.getByRole('button', {name: 'Cancel', exact: true}).click()
  await page.locator('.drive-card').getByRole('button', {name: 'Restore', exact: true}).click()
  await expect(page.locator('.drive-card')).toHaveCount(0)
  expect((await apiContext.delete(`${root}/tasks/1/attachments/${attachment.id}`, {headers})).ok()).toBe(true)
  expect((await apiContext.get(`${root}/drive/files/${file.file_id}/download`, {headers})).status()).toBe(200)
  await page.locator('.drive-toolbar').getByRole('button', {name: 'Back to files', exact: true}).click()
  await page.locator('.drive-card').getByRole('button', {name: 'Move to recycle bin', exact: true}).click()
  await details.getByRole('button', {name: 'Move to recycle bin', exact: true}).click()
  await expect(details).not.toBeVisible()
  await page.locator('.drive-toolbar').getByRole('button', {name: 'Recycle bin', exact: true}).click()
  await page.locator('.drive-card').getByRole('button', {name: 'Details and usages', exact: true}).click()
  await details.getByRole('button', {name: 'Delete permanently', exact: true}).click()
  const purge = details.getByRole('button', {name: 'Delete permanently', exact: true})
  await expect(purge).toBeDisabled()
  await details.getByLabel('Type the full file name to confirm permanent deletion').fill('reusable.txt')
  await purge.click()
  await expect(details).not.toBeVisible()
  await expect(page.locator('.drive-card')).toHaveCount(0)
  expect((await apiContext.get(`${root}/drive/files/${file.file_id}/download`, {headers})).status()).toBe(404)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
 })
}

